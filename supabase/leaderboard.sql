create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 20),
  score integer not null check (score between 0 and 1020),
  level integer not null check (level between 1 and 10),
  created_at timestamptz not null default now()
);

create index if not exists leaderboard_score_created_at_idx
  on public.leaderboard (score desc, created_at asc);

alter table public.leaderboard enable row level security;

grant select, insert on public.leaderboard to service_role;
grant usage, select on sequence public.leaderboard_id_seq to service_role;
