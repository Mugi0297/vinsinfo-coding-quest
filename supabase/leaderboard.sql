create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 80),
  rollno text not null default '' check (char_length(rollno) <= 30),
  department text not null default '' check (char_length(department) <= 80),
  section text not null default '' check (char_length(section) <= 30),
  score integer not null check (score between 0 and 1020),
  level integer not null check (level between 1 and 10),
  created_at timestamptz not null default now()
);

alter table public.leaderboard
  add column if not exists rollno text not null default '' check (char_length(rollno) <= 30),
  add column if not exists department text not null default '' check (char_length(department) <= 80),
  add column if not exists section text not null default '' check (char_length(section) <= 30);

alter table public.leaderboard
  drop constraint if exists leaderboard_name_check,
  drop constraint if exists leaderboard_name_length_check,
  add constraint leaderboard_name_length_check check (char_length(name) between 1 and 80);

create table if not exists public.student_profiles (
  rollno text primary key check (char_length(rollno) between 1 and 30),
  name text not null check (char_length(name) between 1 and 80),
  department text not null check (char_length(department) between 1 and 80),
  section text not null check (char_length(section) between 1 and 30),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.student_attempts (
  id bigint generated by default as identity primary key,
  rollno text not null references public.student_profiles (rollno) on update cascade on delete cascade,
  level integer not null check (level between 1 and 10),
  status text not null default 'in_progress' check (status in ('in_progress', 'completed', 'abandoned')),
  score integer check (score between 0 and 1020),
  correct_answers integer,
  question_count integer not null check (question_count between 1 and 30),
  passed boolean not null default false,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  check (correct_answers is null or correct_answers between 0 and question_count)
);

create index if not exists student_attempts_rollno_started_at_idx
  on public.student_attempts (rollno, started_at desc);
create index if not exists student_attempts_started_at_idx
  on public.student_attempts (started_at desc);
create index if not exists student_attempts_level_passed_idx
  on public.student_attempts (rollno, level, passed);

alter table public.student_profiles enable row level security;
alter table public.student_attempts enable row level security;
revoke all on public.student_profiles, public.student_attempts from public, anon, authenticated;
grant select, insert, update on public.student_profiles to service_role;
grant select, insert, update on public.student_attempts to service_role;
grant usage, select on sequence public.student_attempts_id_seq to service_role;

create index if not exists leaderboard_score_created_at_idx
  on public.leaderboard (score desc, created_at asc);

alter table public.leaderboard enable row level security;

grant select, insert on public.leaderboard to service_role;
grant usage, select on sequence public.leaderboard_id_seq to service_role;

create table if not exists public.leaderboard_submission_limits (
  client_hash text primary key,
  window_started_at timestamptz not null,
  request_count integer not null check (request_count > 0)
);

alter table public.leaderboard_submission_limits enable row level security;

create index if not exists leaderboard_submission_limits_window_idx
  on public.leaderboard_submission_limits (window_started_at);

create or replace function public.consume_leaderboard_submission(
  p_client_hash text,
  p_limit integer,
  p_window_seconds integer
)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
  current_window timestamptz;
  current_count integer;
begin
  if p_client_hash is null or pg_catalog.length(p_client_hash) <> 64
    or p_limit < 1 or p_window_seconds < 1 then
    raise exception 'Invalid rate-limit parameters.';
  end if;

  current_window := pg_catalog.date_bin(
    pg_catalog.make_interval(secs => p_window_seconds),
    pg_catalog.now(),
    timestamptz '2000-01-01 00:00:00+00'
  );

  delete from public.leaderboard_submission_limits
    where window_started_at < current_window - interval '1 day';

  insert into public.leaderboard_submission_limits as limits
    (client_hash, window_started_at, request_count)
  values (p_client_hash, current_window, 1)
  on conflict (client_hash) do update
    set window_started_at = excluded.window_started_at,
        request_count = case
          when limits.window_started_at = excluded.window_started_at
            then limits.request_count + 1
          else 1
        end
  returning request_count into current_count;

  return current_count <= p_limit;
end;
$$;

revoke all on function public.consume_leaderboard_submission(text, integer, integer) from public, anon, authenticated;
grant execute on function public.consume_leaderboard_submission(text, integer, integer) to service_role;
